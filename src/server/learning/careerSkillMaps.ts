const CAREER_SKILL_MAPS_REGISTRY: Record<string, CareerSkillMap> = {
  'ai engineer': AI_ENGINEER_SKILL_MAP,
  'machine learning engineer': AI_ENGINEER_SKILL_MAP,
  'frontend developer': FRONTEND_DEVELOPER_SKILL_MAP,
  'front-end developer': FRONTEND_DEVELOPER_SKILL_MAP,
  'backend developer': BACKEND_DEVELOPER_SKILL_MAP,
  'back-end developer': BACKEND_DEVELOPER_SKILL_MAP,
  'data analyst': DATA_ANALYST_SKILL_MAP,
};

export function getCareerSkillMap(roleTitle: string): CareerSkillMap {
  const normalized = roleTitle.trim().toLowerCase();
  for (const [key, map] of Object.entries(CAREER_SKILL_MAPS_REGISTRY)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return map;
    }
  }

  // If role is a developer role, default to Frontend or Backend, otherwise generate dynamically from baseline
  if (normalized.includes('front') || normalized.includes('web') || normalized.includes('ui')) {
    return { ...FRONTEND_DEVELOPER_SKILL_MAP, role_title: roleTitle };
  }
  if (normalized.includes('back') || normalized.includes('cloud') || normalized.includes('devops')) {
    return { ...BACKEND_DEVELOPER_SKILL_MAP, role_title: roleTitle };
  }
  if (normalized.includes('data') || normalized.includes('analytics')) {
    return { ...DATA_ANALYST_SKILL_MAP, role_title: roleTitle };
  }

  // Standard engineering fallback with real dependencies
  return { ...AI_ENGINEER_SKILL_MAP, role_title: roleTitle };
}
